# prog_fib.S : 上板程序 1, 斐波那契数列第 n 项
#   F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2)
#   n 从 0x2000 读取, 结果写到 0x2004
#=======================================================================
    lui  t0, 0x2
    lw   a1, 0(t0)
    andi a1, a1, 15         # n = SW[3:0]
    addi a0, x0, 0          # f0 = 0
    addi a2, x0, 1          # f1 = 1
    beq  a1, x0, done       # n == 0 时结果为 0
loop:
    add  a3, a0, a2         # f2 = f0 + f1
    mv   a0, a2             # f0 = f1
    mv   a2, a3             # f1 = f2
    addi a1, a1, -1
    bne  a1, x0, loop
done:
    sw   a0, 4(t0)          # F(n)
hang:
    j    hang
