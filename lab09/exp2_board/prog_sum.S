#=======================================================================
# prog_sum.S : 上板程序 0, 累加和 1+2+...+n
#   n 从存储器映射开关端口 0x2000 读取 (SW[3:0]),
#   结果写到 0x2004 (数码管显示).
#=======================================================================
    lui  t0, 0x2            # t0 = 0x2000, 开关端口
    lw   a1, 0(t0)          # a1 = SW
    andi a1, a1, 15         # n = SW[3:0]
    addi a0, x0, 0          # sum = 0
    beq  a1, x0, done       # n == 0 时直接结束
loop:
    add  a0, a0, a1         # sum += n
    addi a1, a1, -1         # n--
    bne  a1, x0, loop
done:
    sw   a0, 4(t0)          # 结果送到显示端口
hang:
    j    hang               # 停机
