#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""make_rom.py : 用 tools/rvasm.py 汇编上板程序, 生成 cpu_top.v 里的 ROM 初始化块

用法:
    python3 make_rom.py                      # 只打印生成的 Verilog 块
    python3 make_rom.py --update prog_rom.v  # 就地替换 prog_rom.v 中的 ROM 块

每个 .S 汇编成一个 256 字的 ROM, 由 SW[15:14] 选择. 程序内地址仍从 0 开始,
分支/跳转都是 PC 相对寻址, 因此不需要关心它在 ROM 中的绝对位置.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))

import rvasm  # noqa: E402

PROGRAMS = [
    ("rom0", "prog_sum.S",   "累加和 1+2+...+n"),
    ("rom1", "prog_fib.S",   "斐波那契 F(n)"),
    ("rom2", "prog_prime.S", "素数判断"),
    ("rom3", "prog_gcd.S",   "最大公约数 gcd(a,b)"),
]

START = "// ==== BEGIN ROM (generated by make_rom.py) ===="
END = "// ==== END ROM ===="


def build_block():
    lines = []
    for idx, (name, fname, desc) in enumerate(PROGRAMS):
        path = os.path.join(HERE, fname)
        with open(path, encoding="utf-8") as f:
            words, _ = rvasm.assemble(f.read())
        if len(words) > 256:
            sys.exit("%s: %d words, 超过 256 字 (1KB)" % (fname, len(words)))
        lines.append("            2'd%d: begin  // %s: %s, %s, %d words"
                     % (idx, name, fname, desc, len(words)))
        lines.append("                case (addr)")
        for i, w in enumerate(words):
            lines.append("                    8'd%3d: dout = 32'h%08x;"
                         % (i, w & 0xFFFFFFFF))
        lines.append("                    default: dout = 32'h00000013;  // nop")
        lines.append("                endcase")
        lines.append("            end")
        lines.append("")
    return "\n".join(lines).rstrip("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", metavar="VFILE")
    args = ap.parse_args()

    block = build_block()
    if not args.update:
        print(block)
        return 0

    with open(args.update, encoding="utf-8") as f:
        v = f.read()
    i = v.find(START)
    j = v.find(END)
    if i < 0 or j < 0 or j < i:
        sys.exit("%s 中没有找到 ROM 生成标记" % args.update)
    v = v[:i + len(START)] + "\n" + block + "\n            " + v[j:]
    with open(args.update, "w", encoding="utf-8") as f:
        f.write(v)
    print("已更新 %s" % args.update)
    return 0


if __name__ == "__main__":
    sys.exit(main())
