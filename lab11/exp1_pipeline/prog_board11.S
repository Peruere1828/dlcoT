    addi x1, x0, 1
    addi x2, x0, 2
    addi x3, x0, 3
loop:
    add  x4, x1, x2
    add  x5, x3, x1
    sw   x4, 0(x0)
    lw   x6, 0(x0)
    beq  x0, x0, loop
